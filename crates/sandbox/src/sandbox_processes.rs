/// Runs [`SANDBOX_PROCESSES_FLAG`] / [`SANDBOX_KILL_FLAG`] and never returns.
/// The caller has already matched the flag.
#[cfg(target_os = "linux")]
pub(crate) fn run_subcommand(listing: bool, arguments: &[std::ffi::OsString]) -> ! {
    let outcome = run_subcommand_inner(listing, arguments);
    match outcome {
        Ok(output) => {
            print!("{output}");
            std::process::exit(0)
        }
        Err(error) => {
            println!("{SANDBOX_PROCESSES_FAILURE_MARKER} {error:#}");
            std::process::exit(1)
        }
    }
}

#[cfg(target_os = "linux")]
fn run_subcommand_inner(listing: bool, arguments: &[std::ffi::OsString]) -> Result<String> {
    let directory = sandbox_sessions_directory_for_this_account()
        .context("the account's home directory is unknown")?;
    let (session_id, rest) = arguments
        .split_first()
        .context("no sandbox session id was given")?;
    let session_id = session_id
        .to_str()
        .context("the sandbox session id is not text")?;
    if listing {
        ensure!(rest.is_empty(), "the listing takes only a session id");
        return Ok(encode_sandbox_processes(&list_sandbox_session_processes(
            &directory, session_id,
        )?));
    }
    let processes = rest
        .iter()
        .map(|argument| {
            argument
                .to_str()
                .and_then(SandboxProcessKey::parse)
                .with_context(|| format!("{argument:?} is not a <pid>:<start time> pair"))
        })
        .collect::<Result<Vec<_>>>()?;
    let stopped = stop_sandbox_session_processes(&directory, session_id, &processes)?;
    Ok(format!("{stopped}\n"))
}

