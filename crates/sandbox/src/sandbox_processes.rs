#[cfg(target_os = "linux")]
pub fn sandbox_sessions_directory_for_this_account() -> Option<PathBuf> {
    let home = crate::protected_paths::home_dir_from_account()?;
    Some(sandbox_sessions_directory(
        &crate::protected_paths::remote_agent_runtime_data_directory(&home),
    ))
}

/// What [`register_sandbox_session`] wrote, as the reader checks it.
#[cfg(target_os = "linux")]
#[derive(Clone, Debug, PartialEq, Eq)]
struct SandboxSessionRegistration {
    /// The helper's parent: the process outside every namespace that wrote
    /// this. A registration whose helper is gone is stale.
    helper: SandboxProcessKey,
    /// The forked holder, which created the namespaces and waits there for
    /// the command. Its `pid_for_children` is what the walk filters `/proc`
    /// by — read when the question is asked rather than recorded here,
    /// because the kernel only gives that link a value once the namespace has
    /// its first process, which is after this is written.
    holder: SandboxProcessKey,
}

#[cfg(target_os = "linux")]
const REGISTRATION_HEADER: &str = "zed-sandbox-session 1";

#[cfg(target_os = "linux")]
impl SandboxSessionRegistration {
    fn encode(&self) -> String {
        format!(
            "{REGISTRATION_HEADER}\nhelper {}\nholder {}\n",
            self.helper.encode(),
            self.holder.encode(),
        )
    }

    fn parse(text: &str) -> Result<Self> {
        let mut lines = text.lines();
        ensure!(
            lines.next() == Some(REGISTRATION_HEADER),
            "not a sandbox session registration"
        );
        let mut helper = None;
        let mut holder = None;
        for line in lines {
            let Some((name, value)) = line.split_once(' ') else {
                continue;
            };
            match name {
                "helper" => helper = SandboxProcessKey::parse(value),
                "holder" => holder = SandboxProcessKey::parse(value),
                _ => {}
            }
        }
        Ok(Self {
            helper: helper.context("the registration names no helper")?,
            holder: holder.context("the registration names no holder")?,
        })
    }

    /// The inode of the command's PID namespace, or `None` where there is
    /// nothing to walk: the holder is gone (and the kernel stopped everything
    /// in its namespace), or it has not put a process in that namespace yet.
    #[cfg(target_os = "linux")]
    fn pid_namespace(&self) -> Option<u64> {
        if process_start_time(self.holder.pid) != Some(self.holder.start_time) {
            return None;
        }
        namespace_inode(&format!("/proc/{}/ns/pid_for_children", self.holder.pid))
    }
}

/// Removes a session's registration when it is dropped. The helper's parent
/// also removes it explicitly on the paths that leave through
/// `std::process::exit`, which no destructor reaches; a registration that
/// survives anyway is harmless, because every reader checks the helper is
/// still running with the start time recorded here.
#[cfg(target_os = "linux")]
pub struct SandboxSessionGuard {
    path: PathBuf,
}

#[cfg(target_os = "linux")]
impl SandboxSessionGuard {
    /// Removes the registration now, for a caller about to `exit`.
    pub fn unregister(&self) {
        if let Err(error) = std::fs::remove_file(&self.path)
            && error.kind() != std::io::ErrorKind::NotFound
        {
            log::warn!(
                "[sandbox-processes] could not remove {}: {error}",
                self.path.display()
            );
        }
    }
}

#[cfg(target_os = "linux")]
impl Drop for SandboxSessionGuard {
    fn drop(&mut self) {
        self.unregister();
    }
}

/// Records the PID namespace `holder_pid` created, so that whatever outside
/// the sandbox holds `session_id` can enumerate it later. Called by the
/// helper's parent — which is outside every namespace — once the holder has
/// reported its namespaces and before the command runs.
#[cfg(target_os = "linux")]
pub(crate) fn register_sandbox_session(
    directory: &std::path::Path,
    session_id: &str,
    holder_pid: i32,
) -> Result<SandboxSessionGuard> {
    validate_sandbox_session_id(session_id)?;
    // SAFETY: `getpid` takes no arguments and cannot fail.
    let helper_pid = unsafe { libc::getpid() };
    let registration = SandboxSessionRegistration {
        helper: SandboxProcessKey {
            pid: helper_pid as u32,
            start_time: process_start_time(helper_pid as u32)
                .context("the helper's own start time")?,
        },
        holder: SandboxProcessKey {
            pid: holder_pid as u32,
            start_time: process_start_time(holder_pid as u32).context("the holder's start time")?,
        },
    };
    create_private_directory(directory)?;
    let path = registration_path(directory, session_id);
    let temporary = path.with_extension("tmp");
    write_private_file(&temporary, registration.encode().as_bytes())?;
    std::fs::rename(&temporary, &path)
        .with_context(|| format!("renaming {} into place", temporary.display()))?;
    Ok(SandboxSessionGuard { path })
}

#[cfg(target_os = "linux")]
fn registration_path(directory: &std::path::Path, session_id: &str) -> PathBuf {
    directory.join(format!("{session_id}.session"))
}

/// Makes the registry directory, as the caller that is about to register a
/// session does before the protected set is pinned: a directory that is there
/// is pinned by its inode rather than by a name that could still be created.
#[cfg(target_os = "linux")]
pub(crate) fn create_sandbox_sessions_directory(directory: &std::path::Path) -> Result<()> {
    create_private_directory(directory)
}

#[cfg(target_os = "linux")]
fn create_private_directory(directory: &std::path::Path) -> Result<()> {
    use std::os::unix::fs::DirBuilderExt as _;
    std::fs::DirBuilder::new()
        .recursive(true)
        .mode(0o700)
        .create(directory)
        .with_context(|| format!("creating {}", directory.display()))
}

#[cfg(target_os = "linux")]
fn write_private_file(path: &std::path::Path, contents: &[u8]) -> Result<()> {
    use std::io::Write as _;
    use std::os::unix::fs::OpenOptionsExt as _;
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o600)
        .open(path)
        .with_context(|| format!("writing {}", path.display()))?;
    file.write_all(contents)
        .with_context(|| format!("writing {}", path.display()))
}

/// The registration of `session_id`, once it is known to belong to a helper
/// that is still running.
///
/// `None` means the sandbox is **gone**, not that the question failed: the
/// helper's parent removes the registration as it exits, and one left behind
/// by a helper that died names a start time no living process carries. Either
/// way the PID namespace died with that helper and the kernel stopped
/// everything in it, so a caller asking what still runs there has its answer,
/// and it is "nothing". A stale file is removed on the way, so a later process
/// that inherits the pid can never stand in for the session.
///
/// An error is kept for what really is a failure to look: a registration that
/// cannot be read or does not parse.
#[cfg(target_os = "linux")]
fn live_registration(
    directory: &std::path::Path,
    session_id: &str,
) -> Result<Option<SandboxSessionRegistration>> {
    validate_sandbox_session_id(session_id)?;
    let path = registration_path(directory, session_id);
    let text = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(error) => return Err(anyhow!("reading {}: {error}", path.display())),
    };
    let registration = SandboxSessionRegistration::parse(&text)?;
    if process_start_time(registration.helper.pid) != Some(registration.helper.start_time) {
        if let Err(error) = std::fs::remove_file(&path)
            && error.kind() != std::io::ErrorKind::NotFound
        {
            log::warn!(
                "[sandbox-processes] could not remove the stale {}: {error}",
                path.display()
            );
        }
        return Ok(None);
    }
    Ok(Some(registration))
}

/// Everything running in the sandbox of `session_id`, newest pid last. Empty
/// for a sandbox that is gone (see [`live_registration`]).
#[cfg(target_os = "linux")]
pub fn list_sandbox_session_processes(
    directory: &std::path::Path,
    session_id: &str,
) -> Result<Vec<SandboxProcess>> {
    let Some(namespace) = live_registration(directory, session_id)?
        .and_then(|registration| registration.pid_namespace())
    else {
        return Ok(Vec::new());
    };
    list_processes_in_pid_namespace(namespace)
}

/// Stops the named processes of `session_id`'s sandbox, and answers how many
/// were signalled. A pid whose start time no longer matches, or that is not in
/// this session's namespace, is skipped: by then it is somebody else's
/// process.
#[cfg(target_os = "linux")]
pub fn stop_sandbox_session_processes(
    directory: &std::path::Path,
    session_id: &str,
    processes: &[SandboxProcessKey],
) -> Result<usize> {
    let Some(namespace) = live_registration(directory, session_id)?
        .and_then(|registration| registration.pid_namespace())
    else {
        return Ok(0);
    };
    Ok(stop_processes_in_pid_namespace(namespace, processes))
}

/// Everything running in the local Bubblewrap sandbox whose `bwrap` process is
/// `root_pid`. Zed spawned it, so the pid is its own handle on the sandbox and
/// no registry is needed; the namespace comes from the child `bwrap` put in it
/// (`--unshare-pid`). Empty once that `bwrap` has exited, which takes its PID
/// namespace and everything in it along.
#[cfg(target_os = "linux")]
pub fn list_local_sandbox_processes(root_pid: u32) -> Result<Vec<SandboxProcess>> {
    let Some(namespace) = local_sandbox_pid_namespace(root_pid)? else {
        return Ok(Vec::new());
    };
    list_processes_in_pid_namespace(namespace)
}

/// Stops the named processes of that same sandbox.
#[cfg(target_os = "linux")]
pub fn stop_local_sandbox_processes(
    root_pid: u32,
    processes: &[SandboxProcessKey],
) -> Result<usize> {
    let Some(namespace) = local_sandbox_pid_namespace(root_pid)? else {
        return Ok(0);
    };
    Ok(stop_processes_in_pid_namespace(namespace, processes))
}

/// The PID namespace `bwrap` made: `bwrap` itself stays outside it (it maps
/// ids and waits there), and the single child it clones is the namespace's
/// init. `None` where there is nothing to walk — `bwrap` is gone and took the
/// namespace with it, or it has not cloned that child yet, which is the
/// ordinary state in the moment after it was spawned. Both read as "no process
/// of this sandbox", and the caller looks again.
#[cfg(target_os = "linux")]
fn local_sandbox_pid_namespace(root_pid: u32) -> Result<Option<u64>> {
    let own = namespace_inode("/proc/self/ns/pid").context("this process's PID namespace")?;
    for child in children_of(root_pid) {
        let Some(inode) = namespace_inode(&format!("/proc/{child}/ns/pid")) else {
            continue;
        };
        if inode != own {
            return Ok(Some(inode));
        }
    }
    Ok(None)
}

#[cfg(target_os = "linux")]
fn children_of(pid: u32) -> Vec<u32> {
    // `children` is per-thread, and the sandbox's parent is single-threaded
    // where it forks, so the main thread's list is the whole list.
    std::fs::read_to_string(format!("/proc/{pid}/task/{pid}/children"))
        .map(|text| {
            text.split_ascii_whitespace()
                .filter_map(|field| field.parse().ok())
                .collect()
        })
        .unwrap_or_default()
}

/// Walks `/proc` — which is the host's, outside every namespace the sandbox
/// built — and keeps the processes that run in `namespace_inode` or in a PID
/// namespace nested inside it.
#[cfg(target_os = "linux")]
pub fn list_processes_in_pid_namespace(namespace_inode: u64) -> Result<Vec<SandboxProcess>> {
    let uptime = host_uptime();
    let ticks_per_second = clock_ticks_per_second();
    // A host runs many processes and they share a handful of PID namespaces
    // between them, so each namespace is followed up the chain once.
    let mut nested = std::collections::HashMap::new();
    let mut processes = Vec::new();
    let entries = std::fs::read_dir("/proc").context("reading /proc")?;
    for entry in entries {
        let Ok(entry) = entry else {
            continue;
        };
        let Some(pid) = entry
            .file_name()
            .to_str()
            .and_then(|name| name.parse::<u32>().ok())
        else {
            continue;
        };
        let Some(own_namespace) = namespace_inode_of(pid) else {
            continue;
        };
        if own_namespace != namespace_inode
            && !*nested
                .entry(own_namespace)
                .or_insert_with(|| nested_in_pid_namespace(pid, namespace_inode))
        {
            continue;
        }
        // Read after the namespace matched, so a process that exits in between
        // drops out instead of being reported with an empty command line.
        let Some(start_time) = live_process_start_time(pid) else {
            continue;
        };
        processes.push(SandboxProcess {
            pid,
            start_time,
            running_for: running_for(start_time, uptime, ticks_per_second),
            command: sanitized_command(&command_line(pid)),
        });
    }
    processes.sort();
    Ok(processes)
}

#[cfg(target_os = "linux")]
fn namespace_inode_of(pid: u32) -> Option<u64> {
    namespace_inode(&format!("/proc/{pid}/ns/pid"))
}

/// How deep PID namespaces nest before the kernel refuses another one.
#[cfg(target_os = "linux")]
const MAX_PID_NAMESPACE_DEPTH: usize = 32;

/// Whether `pid` runs in `namespace_inode` or in a PID namespace made inside
/// it.
///
/// Nothing in the sandbox stops the command from making namespaces of its own:
/// an unprivileged user namespace costs no privilege, and inside one
/// `CLONE_NEWPID` is free. What it puts there still runs in the sandbox and
/// still writes the worktree, so the chain is followed upwards rather than the
/// leaf compared — otherwise a single `unshare` would be all it takes to leave
/// a process behind that this never reports.
#[cfg(target_os = "linux")]
fn in_pid_namespace(pid: u32, namespace_inode: u64) -> bool {
    match namespace_inode_of(pid) {
        Some(own_namespace) if own_namespace == namespace_inode => true,
        Some(_) => nested_in_pid_namespace(pid, namespace_inode),
        None => false,
    }
}

#[cfg(target_os = "linux")]
fn nested_in_pid_namespace(pid: u32, namespace_inode: u64) -> bool {
    let Ok(mut namespace) = std::fs::File::open(format!("/proc/{pid}/ns/pid")) else {
        return false;
    };
    for _ in 0..MAX_PID_NAMESPACE_DEPTH {
        let Some(parent) = parent_pid_namespace(&namespace) else {
            return false;
        };
        if file_inode(&parent) == Some(namespace_inode) {
            return true;
        }
        namespace = parent;
    }
    false
}

/// `NS_GET_PARENT` (`_IO(0xb7, 0x2)`): the namespace a nested one was made
/// from. `None` at the top of what this process may see — asking above its own
/// namespace is `EPERM` — and on a kernel from before it existed (4.9), where
/// a nested namespace goes back to looking like somebody else's.
#[cfg(target_os = "linux")]
fn parent_pid_namespace(namespace: &std::fs::File) -> Option<std::fs::File> {
    use std::os::fd::{AsRawFd as _, FromRawFd as _};

    const NS_GET_PARENT: u32 = 0xb702;
    // SAFETY: `ioctl` with a scalar request that reads no memory and answers
    // with a new file descriptor.
    let parent = unsafe { libc::ioctl(namespace.as_raw_fd(), NS_GET_PARENT as _) };
    if parent < 0 {
        return None;
    }
    // SAFETY: the kernel has just made this descriptor and nothing else owns
    // it, so the `File` is its only owner.
    Some(unsafe { std::fs::File::from_raw_fd(parent) })
}

/// A namespace file's inode is the namespace's own identity — the number
/// `/proc/<pid>/ns/*` spells in its link.
#[cfg(target_os = "linux")]
fn file_inode(file: &std::fs::File) -> Option<u64> {
    use std::os::unix::fs::MetadataExt as _;
    Some(file.metadata().ok()?.ino())
}

#[cfg(target_os = "linux")]
fn namespace_inode(path: &str) -> Option<u64> {
    let link = std::fs::read_link(path).ok()?;
    parse_namespace_link(link.to_str()?)
}

/// `pid:[4026532567]` — the only spelling `/proc/<pid>/ns/*` has.
#[cfg(any(target_os = "linux", test))]
fn parse_namespace_link(link: &str) -> Option<u64> {
    let inode = link.split_once(":[")?.1.strip_suffix(']')?;
    inode.parse().ok()
}

/// Seconds this host has been up, from `/proc/uptime`. `None` where it cannot
/// be read, which leaves every process's running time unknown rather than
/// wrong.
#[cfg(target_os = "linux")]
fn host_uptime() -> Option<f64> {
    std::fs::read_to_string("/proc/uptime")
        .ok()?
        .split_ascii_whitespace()
        .next()?
        .parse()
        .ok()
}

#[cfg(target_os = "linux")]
fn clock_ticks_per_second() -> Option<f64> {
    // SAFETY: `sysconf` with a scalar argument reads no memory.
    let ticks = unsafe { libc::sysconf(libc::_SC_CLK_TCK) };
    (ticks > 0).then(|| ticks as f64)
}

/// How long a process whose `/proc` start time is `start_time` has been
/// running. Zero where either half is unknown: the dialog then shows no age
/// rather than an invented one.
#[cfg(any(target_os = "linux", test))]
fn running_for(
    start_time: u64,
    uptime: Option<f64>,
    ticks_per_second: Option<f64>,
) -> std::time::Duration {
    let (Some(uptime), Some(ticks_per_second)) = (uptime, ticks_per_second) else {
        return std::time::Duration::ZERO;
    };
    let seconds = uptime - start_time as f64 / ticks_per_second;
    if !seconds.is_finite() || seconds <= 0.0 {
        return std::time::Duration::ZERO;
    }
    std::time::Duration::from_secs(seconds as u64)
}

/// Ticks since boot at which `pid` started, from `/proc/<pid>/stat`.
#[cfg(target_os = "linux")]
fn process_start_time(pid: u32) -> Option<u64> {
    Some(parse_stat(&std::fs::read_to_string(format!("/proc/{pid}/stat")).ok()?)?.1)
}

/// The same, but `None` for a process that has already ended and only waits to
/// be reaped. A zombie holds nothing open, so it writes nothing and no answer
/// left it running; a signal would also never make it go away, which would
/// leave a worktree paused with a process the user cannot stop.
#[cfg(target_os = "linux")]
fn live_process_start_time(pid: u32) -> Option<u64> {
    match parse_stat(&std::fs::read_to_string(format!("/proc/{pid}/stat")).ok()?)? {
        (ZOMBIE_STATE, _) => None,
        (_, start_time) => Some(start_time),
    }
}

#[cfg(any(target_os = "linux", test))]
const ZOMBIE_STATE: char = 'Z';

/// `/proc/<pid>/stat` fields 3 (the state) and 22 (the start time). Everything
/// before the last `)` is the pid and the command name, which may itself hold
/// spaces and parentheses; the fields after it are plain and start at field 3.
#[cfg(any(target_os = "linux", test))]
fn parse_stat(stat: &str) -> Option<(char, u64)> {
    let after_name = stat.rsplit_once(')')?.1;
    let mut fields = after_name.split_ascii_whitespace();
    let state = fields.next()?.chars().next()?;
    Some((state, fields.nth(18)?.parse().ok()?))
}

/// `pid`'s command line, or its thread name where it has none (a kernel-side
/// process, or one that cleared its own `argv`).
#[cfg(target_os = "linux")]
fn command_line(pid: u32) -> String {
    let raw = std::fs::read(format!("/proc/{pid}/cmdline")).unwrap_or_default();
    let command = raw
        .split(|byte| *byte == 0)
        .filter(|argument| !argument.is_empty())
        .map(|argument| String::from_utf8_lossy(argument).into_owned())
        .collect::<Vec<_>>()
        .join(" ");
    if !command.trim().is_empty() {
        return command;
    }
    std::fs::read_to_string(format!("/proc/{pid}/comm")).unwrap_or_default()
}

/// How long the listed processes get to stop on their own before the rest is
/// killed.
#[cfg(target_os = "linux")]
const STOP_GRACE: std::time::Duration = std::time::Duration::from_millis(2000);

#[cfg(target_os = "linux")]
const STOP_POLL: std::time::Duration = std::time::Duration::from_millis(100);

/// Signals the named processes, but only where the pid is still in
/// `namespace_inode` **and** still carries the start time the caller saw:
/// otherwise the pid has been recycled and belongs to someone else.
#[cfg(target_os = "linux")]
#[allow(
    clippy::disallowed_methods,
    reason = "runs either in the standalone helper utility or on a background \
              thread of the remote server, never on a GPUI foreground thread"
)]
fn stop_processes_in_pid_namespace(namespace_inode: u64, processes: &[SandboxProcessKey]) -> usize {
    let mut signalled = Vec::new();
    for process in processes {
        if signal_if_still_itself(namespace_inode, process, libc::SIGTERM) {
            signalled.push(*process);
        }
    }
    let deadline = std::time::Instant::now() + STOP_GRACE;
    while std::time::Instant::now() < deadline {
        if signalled
            .iter()
            .all(|process| !still_itself(namespace_inode, process))
        {
            return signalled.len();
        }
        std::thread::sleep(STOP_POLL);
    }
    for process in &signalled {
        signal_if_still_itself(namespace_inode, process, libc::SIGKILL);
    }
    signalled.len()
}

#[cfg(target_os = "linux")]
fn still_itself(namespace_inode: u64, process: &SandboxProcessKey) -> bool {
    live_process_start_time(process.pid) == Some(process.start_time)
        && in_pid_namespace(process.pid, namespace_inode)
}

#[cfg(target_os = "linux")]
fn signal_if_still_itself(
    namespace_inode: u64,
    process: &SandboxProcessKey,
    signal: libc::c_int,
) -> bool {
    if !still_itself(namespace_inode, process) {
        return false;
    }
    // SAFETY: `kill` with scalar arguments. The checks above ran against the
    // same pid, so the only window left is a process exiting in between, which
    // makes this an ESRCH, not a signal to someone else — the kernel does not
    // reuse a pid while its parent has not reaped it, and everything in this
    // namespace is reaped by its own init.
    if unsafe { libc::kill(process.pid as libc::pid_t, signal) } != 0 {
        let error = std::io::Error::last_os_error();
        if error.kind() != std::io::ErrorKind::NotFound {
            log::warn!("[sandbox-processes] kill({}): {error}", process.pid);
        }
        return false;
    }
    true
}

