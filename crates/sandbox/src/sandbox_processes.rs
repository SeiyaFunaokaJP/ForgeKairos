/// this directory in its own protected set, so the protection does not depend
/// on the data directory's spelling matching the built-in entry.
#[cfg(target_os = "linux")]
pub(crate) const SANDBOX_SESSIONS_DIRECTORY_NAME: &str = "sandbox-sessions";

#[cfg(target_os = "linux")]
pub(crate) fn sandbox_sessions_directory(data_directory: &std::path::Path) -> PathBuf {
    data_directory.join(SANDBOX_SESSIONS_DIRECTORY_NAME)
}

/// The same directory worked out from the process's own environment, for a
