//! ADR-F49 decision 18 (C): what still runs inside an agent's sandbox, seen
//! only from **outside** it.
//!
//! ADR-F50 pauses a worktree's own code until the user has looked at what an
//! agent wrote. An agent that leaves a process behind — a development server,
//! an MCP server it started mid-answer — can still write after its answer ends,
//! so the answer's writer registration has to last until that process does.
//! Deciding that needs a list of what runs in the sandbox, and the list must
//! not come from inside it: every channel the command can write (its stderr,
//! a file in the worktree) it can also lie on.
//!
//! So the trusted side does the looking:
//!
//! * **Remote (SSH / WSL / Docker helper)**: the helper's parent — which lives
//!   outside every namespace it builds — records the command's PID namespace
//!   in a directory the sandbox cannot write ([`register_sandbox_session`]),
//!   under an opaque id the client generated. Anything outside the sandbox
//!   that can read that directory can then enumerate the namespace
//!   ([`list_sandbox_session_processes`]) and stop what it names
//!   ([`stop_sandbox_session_processes`]). On an SSH host the remote server
//!   does this in-process; the Windows backend runs the same binary as a
//!   short-lived utility ([`SANDBOX_PROCESSES_FLAG`],
//!   [`SANDBOX_KILL_FLAG`]).
//! * **Local Linux (Bubblewrap)**: Zed spawns `bwrap` itself, so it holds the
//!   only handle that matters — the child's pid — and reads `/proc` through
//!   the PID namespace that child made ([`list_local_sandbox_processes`]).
//! * **macOS (Seatbelt)** has no such boundary, so there is no implementation
//!   here and the caller falls back to keeping the writer for the whole
//!   session (ADR-F49 decision 18, case B).
//!
//! A pid alone is not an identity — the kernel reuses them — so every process
//! is named by its pid **and** its start time ([`SandboxProcessKey`]), and a
//! stop request only ever signals a process whose start time still matches.

#[cfg(target_os = "linux")]
use anyhow::anyhow;
use anyhow::{Context as _, Result, bail, ensure};
#[cfg(target_os = "linux")]
use std::path::PathBuf;

/// ADR-F49 decision 18: prints the processes of the sandbox session named by
/// the following argument, one per line (see [`encode_sandbox_processes`]).
pub const SANDBOX_PROCESSES_FLAG: &str = "--sandbox-processes";

/// ADR-F49 decision 18: stops the listed processes of the sandbox session
/// named by the following argument. The remaining arguments are
/// `<pid>:<start time>` pairs (see [`SandboxProcessKey::encode`]).
pub const SANDBOX_KILL_FLAG: &str = "--sandbox-kill";

/// Opens the one line either subcommand prints when it cannot answer, so a
/// caller reading its output can tell a refusal from an empty list.
pub const SANDBOX_PROCESSES_FAILURE_MARKER: &str = "zed-sandbox-processes-error:";

/// The longest a session id may be; ids are generated by Zed, so this only has
/// to be roomy enough for a UUID.
const MAX_SESSION_ID_LENGTH: usize = 64;

/// How much of a command line is kept for display.
#[cfg(any(target_os = "linux", test))]
const MAX_COMMAND_LENGTH: usize = 160;

/// A process running inside a sandbox, as the trusted side sees it.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct SandboxProcess {
    /// The pid **on the host**, which is what a stop request signals — never
    /// the pid the process sees inside its own namespace.
    pub pid: u32,
    /// Ticks since boot at which the process started (`/proc/<pid>/stat`
    /// field 22). Paired with the pid so a recycled pid is never mistaken for
    /// the process that held it.
    pub start_time: u64,
    /// How long it has been running, worked out on the host it runs on: its
    /// start time is in that kernel's ticks since that host's boot, which
    /// means nothing anywhere else.
    pub running_for: std::time::Duration,
    /// Its command line, for the user to recognize it by. This is the one
    /// piece of the report the sandboxed command chooses, so it carries no
    /// control characters and is truncated.
    pub command: String,
}

impl SandboxProcess {
    pub fn key(&self) -> SandboxProcessKey {
        SandboxProcessKey {
            pid: self.pid,
            start_time: self.start_time,
        }
    }
}

/// What names a process across a report and a later stop request.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct SandboxProcessKey {
    pub pid: u32,
    pub start_time: u64,
}

impl SandboxProcessKey {
    /// `<pid>:<start time>`, as the stop subcommand takes it.
    pub fn encode(&self) -> String {
        format!("{}:{}", self.pid, self.start_time)
    }

    pub fn parse(text: &str) -> Option<Self> {
        let (pid, start_time) = text.split_once(':')?;
        Some(Self {
            pid: pid.parse().ok()?,
            start_time: start_time.parse().ok()?,
        })
    }
}

/// Whether `id` is one this crate will look up: a session id becomes a file
/// name in the registry, so nothing but unreserved ASCII is allowed through.
/// Checked on both sides — the client that generates it and the host that
/// reads it — so no id can ever name a path.
pub fn validate_sandbox_session_id(id: &str) -> Result<()> {
    ensure!(
        !id.is_empty() && id.len() <= MAX_SESSION_ID_LENGTH,
        "a sandbox session id is 1 to {MAX_SESSION_ID_LENGTH} characters"
    );
    ensure!(
        id.bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-' || byte == b'_'),
        "a sandbox session id holds only letters, digits, '-' and '_'"
    );
    Ok(())
}

/// One line per process: `<pid> <start time> <seconds running> <command as
/// lowercase hex>`.
///
/// The command is hex so that the only attacker-chosen part of the report
/// cannot forge a line, a marker or a field separator on its way through a
/// pipe — `wsl.exe`'s standard output, an SSH channel — even though it is
/// sanitized before it gets here.
pub fn encode_sandbox_processes(processes: &[SandboxProcess]) -> String {
    let mut encoded = String::new();
    for process in processes {
        let command = process
            .command
            .bytes()
            .map(|byte| format!("{byte:02x}"))
            .collect::<String>();
        encoded.push_str(&format!(
            "{} {} {} {command}\n",
            process.pid,
            process.start_time,
            process.running_for.as_secs()
        ));
    }
    encoded
}

/// The counterpart of [`encode_sandbox_processes`]. A line that does not
/// decode fails the whole report: a partial list would read as "nothing is
/// left running", which is the answer that lets the user resume.
pub fn decode_sandbox_processes(output: &str) -> Result<Vec<SandboxProcess>> {
    let mut processes = Vec::new();
    for line in output.lines() {
        let line = line.trim_end_matches('\r');
        if line.is_empty() {
            continue;
        }
        if let Some(detail) = line.strip_prefix(SANDBOX_PROCESSES_FAILURE_MARKER) {
            bail!("the host refused to list the sandbox's processes:{detail}");
        }
        let mut fields = line.split(' ');
        let (Some(pid), Some(start_time), Some(running_for), Some(command), None) = (
            fields.next(),
            fields.next(),
            fields.next(),
            fields.next(),
            fields.next(),
        ) else {
            bail!("a sandbox process line has {line:?} instead of four fields");
        };
        processes.push(SandboxProcess {
            pid: pid.parse().context("a sandbox process line's pid")?,
            start_time: start_time
                .parse()
                .context("a sandbox process line's start time")?,
            running_for: std::time::Duration::from_secs(
                running_for
                    .parse()
                    .context("a sandbox process line's running time")?,
            ),
            command: decode_command(command)?,
        });
    }
    Ok(processes)
}

fn decode_command(hex: &str) -> Result<String> {
    ensure!(
        hex.len().is_multiple_of(2) && hex.bytes().all(|byte| byte.is_ascii_hexdigit()),
        "a sandbox process line's command is not hex"
    );
    let bytes = (0..hex.len())
        .step_by(2)
        .map(|index| {
            hex.get(index..index + 2)
                .and_then(|pair| u8::from_str_radix(pair, 16).ok())
                .context("a sandbox process line's command is not hex")
        })
        .collect::<Result<Vec<u8>>>()?;
    String::from_utf8(bytes).context("a sandbox process line's command is not UTF-8")
}

/// What a sandboxed command may put in a report the user reads: printable
/// text, one line, bounded. Applied where the command line is read, so no
/// caller can forget it. Empty for a process with no command line of its own,
/// which the side that renders the report says in the user's language.
#[cfg(any(target_os = "linux", test))]
fn sanitized_command(raw: &str) -> String {
    let mut command: String = raw
        .chars()
        .map(|character| {
            if character.is_control() || character == '\u{fffd}' {
                ' '
            } else {
                character
            }
        })
        .collect();
    command = command.split_whitespace().collect::<Vec<_>>().join(" ");
    if command.chars().count() > MAX_COMMAND_LENGTH {
        command = command
            .chars()
            .take(MAX_COMMAND_LENGTH.saturating_sub(1))
            .collect::<String>()
            + "…";
    }
    command
}

